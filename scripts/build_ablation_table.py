#!/usr/bin/env python3
"""Aggregate ablation eval exports into a LaTeX table (mean +/- std over seeds).

Reads the JSON files produced by eval_rq1_export.py for each (kg, ablation,
seed) combination and emits a table with one row per ablation variant,
mean +/- std across seeds, ready to paste into tables/tab-ablation.tex.

Usage:
    python scripts/build_ablation_table.py \
        --glob "results/significance/{kg}_seed*_{ablation}.json" \
        --kgs dbpedia wikidata \
        --ablations full no_gnn no_decomposition \
        --out tables/tab-ablation.tex
"""
import argparse
import glob
import json
from pathlib import Path

import numpy as np

METRIC = "mrr@10"
NDCG_METRIC = "ndcg@10"

LABELS = {
    "full": "\\textsc{SparqlCE} (full)",
    "no_gnn": "\\quad -- GATv2 message passing (bag of nodes)",
    "no_decomposition": "\\quad -- graph decomposition (whole-query text)",
}


def load_metric(pattern, kg, ablation, metric):
    files = sorted(glob.glob(pattern.format(kg=kg, ablation=ablation)))
    vals = []
    for path in files:
        with open(path) as f:
            d = json.load(f)
        if d.get("ablation") == ablation:
            vals.append(d["aggregate"][metric])
    return vals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glob", required=True,
                     help="pattern with {kg} and {ablation} placeholders, e.g. "
                          "'results/significance/{kg}_seed*_{ablation}.json'")
    ap.add_argument("--kgs", nargs="+", default=["dbpedia", "wikidata"])
    ap.add_argument("--ablations", nargs="+", default=["full", "no_gnn", "no_decomposition"])
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    lines = [
        "% Auto-generated by scripts/build_ablation_table.py -- do not hand-edit.",
        "\\begin{table}[t]",
        "  \\caption{Architectural ablation: MRR@10 / nDCG@10, mean $\\pm$ std over "
        "seeds (full-corpus ranking, RQ$_1$ test set).}",
        "  \\label{tab:ablation}",
        "  \\centering",
        "  \\begin{tabular}{@{}lcccc@{}}",
        "    \\toprule",
        "     & \\multicolumn{2}{c}{\\textbf{DBpedia}} & \\multicolumn{2}{c}{\\textbf{Wikidata}} \\\\",
        "    \\cmidrule(lr){2-3} \\cmidrule(lr){4-5}",
        "    \\textbf{Variant} & MRR@10 & nDCG@10 & MRR@10 & nDCG@10 \\\\",
        "    \\midrule",
    ]

    missing = []
    for ablation in args.ablations:
        row = [LABELS.get(ablation, ablation)]
        for kg in args.kgs:
            mrr_vals = load_metric(args.glob, kg, ablation, METRIC)
            ndcg_vals = load_metric(args.glob, kg, ablation, NDCG_METRIC)
            if not mrr_vals or not ndcg_vals:
                missing.append((kg, ablation))
                row += ["--", "--"]
                continue
            row.append(f"{np.mean(mrr_vals):.4f}$\\pm${np.std(mrr_vals, ddof=1) if len(mrr_vals) > 1 else 0:.4f}")
            row.append(f"{np.mean(ndcg_vals):.4f}$\\pm${np.std(ndcg_vals, ddof=1) if len(ndcg_vals) > 1 else 0:.4f}")
        lines.append("    " + " & ".join(row) + " \\\\")

    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}"]

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out_path}")
    if missing:
        print("WARNING: no results found for:")
        for kg, ablation in missing:
            print(f"  kg={kg} ablation={ablation}")


if __name__ == "__main__":
    main()
